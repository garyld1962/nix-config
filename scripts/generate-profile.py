#!/usr/bin/env python3
"""Write a generated, non-secret Home Manager profile outside the shared repo."""
import argparse
import json
import re
from pathlib import Path

MARKER = "# Generated by nix-config; personal settings belong in a separate installer."
# Optional modules are exported by the shared flake as homeModules.<name>.
MODULE_NAME = re.compile(r"[a-z][a-z0-9-]*")


def nix_string(value):
    return json.dumps(value, ensure_ascii=False).replace("${", r"\${")


def generate(root, destination, username, home, modules=()):
    if not username or not home.startswith("/"):
        raise ValueError("A username and absolute home directory are required.")
    modules = list(dict.fromkeys(modules))
    for module in modules:
        if not MODULE_NAME.fullmatch(module):
            raise ValueError(f"Invalid module name: {module!r} (use lowercase letters, digits, and -).")
    extra = " ".join(f"shared-dev.homeModules.{module}" for module in modules)
    if not (root / "flake.lock").is_file():
        raise ValueError("The shared flake.lock is required; refusing to select new versions.")
    destination.mkdir(parents=True, exist_ok=True)
    target = destination / "flake.nix"
    if target.exists() and not target.read_text().startswith(MARKER + "\n"):
        raise ValueError(f"Refusing to replace a manually maintained profile: {target}")
    content = f'''{MARKER}
{{
  description = "Shared developer environment for this account";
  inputs.shared-dev = {{
    type = "path";
    path = {nix_string(str(root.resolve()))};
  }};
  outputs = {{ shared-dev, ... }}: {{
    homeConfigurations.default = shared-dev.lib.mkHomeConfiguration {{
      username = {nix_string(username)};
      homeDirectory = {nix_string(home)};
      extraModules = [ {extra} ];
    }};
  }};
}}
'''
    if not target.exists() or target.read_text() != content:
        temporary = destination / "flake.nix.tmp"
        temporary.write_text(content)
        temporary.replace(target)
    return target


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", required=True, type=Path)
    parser.add_argument("--destination", required=True, type=Path)
    parser.add_argument("--username", required=True)
    parser.add_argument("--home", required=True)
    parser.add_argument("--module", action="append", default=[],
                        help="optional shared module to enable (repeatable)")
    args = parser.parse_args()
    try:
        generate(args.root, args.destination, args.username, args.home, args.module)
    except ValueError as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
